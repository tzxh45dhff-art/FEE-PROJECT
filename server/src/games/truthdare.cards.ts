/**
 * Truth or dare, the cards.
 *
 * Written for people in different places, on a call: every dare can be done in
 * front of a camera or a microphone, none of them involve anyone outside the
 * room (no "text your ex", no posting for you), and none of them ask anyone to
 * hurt themselves or embarrass somebody who isn't playing. The asker picks from
 * these, so the bar is "would I actually choose this card" — a deck of fillers
 * is a deck nobody plays twice.
 *
 * Spicy is for adults, behind an explicit 18+ confirmation when the game
 * starts. It is flirty and bold, not explicit: the point is the look on the
 * other person's face, not a description of anything.
 */

export const DECKS = ['funny', 'friends', 'couples', 'deep', 'spicy'] as const
export type Deck = (typeof DECKS)[number]
export type Kind = 'truth' | 'dare'

export const cardTextKey = (text: string) => text.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim()

/** Rewriting a card makes it new; reordering the deck does not erase its history. */
export const bankCardId = (deck: Deck, kind: Kind, text: string) =>
  `bank:${deck}:${kind}:${createHash('sha1').update(cardTextKey(text)).digest('hex').slice(0, 12)}`

